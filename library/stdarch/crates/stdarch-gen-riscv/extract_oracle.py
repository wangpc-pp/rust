#!/usr/bin/env python3
"""Extract reproducible RVV lowering data from clang's generated tests.

The legacy broad-scan invocation is kept intact::

    extract_oracle.py <clang-autogen-root> <out-file>

The checked-in Rust lowering and policy inventories are reproduced from the
repository root with::

    python3 library/stdarch/crates/stdarch-gen-riscv/extract_oracle.py \
      src/llvm-project/clang/test/CodeGen/RISCV/rvv-intrinsics-autogenerated \
      /tmp/rvv_lowering.tsv --rust-lowering \
      --clang build/.../llvm/bin/clang \
      --policy-out /tmp/rvv_policy.tsv
    cmp /tmp/rvv_lowering.tsv \
      library/stdarch/crates/stdarch-gen-riscv/spec/vector/rvv_lowering.tsv
    cmp /tmp/rvv_policy.tsv \
      library/stdarch/crates/stdarch-gen-riscv/spec/vector/rvv_policy.tsv

It writes a three-column lowering TSV whose literal operands carry their LLVM
type (`#iN:value` or `#xlen:value`).  ``--policy-out`` also
writes a strict policy-surface manifest whose records are::

    <scope>\t<complete C prototype>\t<llvm name>\t<operand recipe>

The policy input is deliberately narrower than the legacy scan.  Its explicit
default allowlist contains the non-overloaded policy tests for base, zvabd,
zvdot4a8i, zvzip, the three bfloat extensions, vector-crypto, and Zvfofp8min.
Sources can be replaced explicitly with
``--policy-source`` for focused extraction or for mapping crypto files to
individual feature scopes.

``--rust-lowering`` selects only lowering owned by the checked-in oracle. It
scans only base, zvabd, zvdot4a8i, and zvzip from the autogenerated tree. From
those sources it omits segment operations handled by compiler bridges and BF16
operations handled programmatically or derived from siblings. It then adds the
200 standard Zvfofp8min APIs from its autogenerated extension directory. Expected
source, exclusion, and result counts are checked so a changed Clang surface
cannot be accepted silently.

Both modes are strict for units in scope: malformed comma lists, unknown C call
tokens, a missing llvm.riscv call, opaque LLVM operands, and conflicting
duplicates are errors.  Exact duplicates are accepted and counted.
"""

