class ExtractError(RuntimeError):
    """A source error which must prevent a partial manifest from escaping."""


@dataclass(frozen=True)
class Param:
    declaration: str
    name: str


@dataclass(frozen=True)
class Unit:
    path: Path
    line: int
    check: str
    return_type: str
    wrapper_name: str
    wrapper_params: Tuple[Param, ...]
    intrinsic_name: str
    call_args: Tuple[str, ...]

    def where(self) -> str:
        return f"{self.path}:{self.line}: {self.intrinsic_name}"


@dataclass(frozen=True)
class Entry:
    llvm: str
    ops: Tuple[str, ...]
    prototype: str
    signature: Tuple[str, ...]
    source: str


def die(message: str) -> ExtractError:
    return ExtractError(message)


def split_top_level(text: str, context: str) -> List[str]:
    """Split a comma list without splitting nested (), [], {}, or <>."""
    pairs = {")": "(", "}": "{", "]": "[", ">": "<"}
    stack: List[str] = []
    fields: List[str] = []
    start = 0
    quote: Optional[str] = None
    escaped = False
    filecheck = False
    skip_filecheck_close = False
    for index, char in enumerate(text):
        if skip_filecheck_close:
            skip_filecheck_close = False
            continue
        if not filecheck and text.startswith("[[", index):
            filecheck = True
            continue
        if filecheck:
            if text.startswith("]]", index):
                filecheck = False
                skip_filecheck_close = True
            continue
        if quote is not None:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = None
            continue
        if char in ("'", '"'):
            quote = char
        elif char in "([{<":
            stack.append(char)
        elif char in pairs:
            if not stack or stack[-1] != pairs[char]:
                raise die(f"{context}: unbalanced delimiter {char!r}")
            stack.pop()
        elif char == "," and not stack:
            field = text[start:index].strip()
            if not field:
                raise die(f"{context}: empty item in comma list")
            fields.append(field)
            start = index + 1
    if quote is not None:
        raise die(f"{context}: unterminated string literal")
    if filecheck:
        raise die(f"{context}: unterminated FileCheck placeholder")
    if stack:
        raise die(f"{context}: unbalanced delimiter {stack[-1]!r}")
    tail = text[start:].strip()
    if tail:
        fields.append(tail)
    elif fields:
        raise die(f"{context}: trailing comma")
    return fields


def balanced_contents(text: str, open_index: int, context: str) -> Tuple[str, int]:
    """Return the contents and end offset of a balanced parenthesized list."""
    if open_index >= len(text) or text[open_index] != "(":
        raise die(f"{context}: expected '('")
    depth = 0
    quote: Optional[str] = None
    escaped = False
    for index in range(open_index, len(text)):
        char = text[index]
        if quote is not None:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == quote:
                quote = None
            continue
        if char in ("'", '"'):
            quote = char
        elif char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
            if depth == 0:
                return text[open_index + 1 : index], index + 1
            if depth < 0:
                break
    raise die(f"{context}: unterminated parenthesized list")


def normalize_space(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def parse_params(text: str, context: str) -> Tuple[Param, ...]:
    fields = split_top_level(text, context)
    if not fields or (len(fields) == 1 and fields[0] == "void"):
        return ()
    result = []
    for declaration in fields:
        declaration = normalize_space(declaration)
        names = list(IDENT.finditer(declaration))
        if not names:
            raise die(f"{context}: parameter has no name: {declaration!r}")
        result.append(Param(declaration, names[-1].group(0)))
    return tuple(result)


def parse_unit(
    path: Path, block: str, line: int, leading_return_type: Optional[str] = None
) -> Unit:
    context = f"{path}:{line}"
    label = LABEL.search(block)
    if not label:
        raise die(f"{context}: malformed CHECK-RV64-LABEL")

    wrapper = WRAPPER.search(block)
    if not wrapper:
        raise die(f"{context}: no test_ wrapper after CHECK-RV64-LABEL")
    wrapper_params, wrapper_end = balanced_contents(
        block, wrapper.end() - 1, f"{context}: wrapper parameters"
    )
    return_type = normalize_space(wrapper.group("return"))
    if not return_type:
        return_type = leading_return_type or ""
    if not return_type:
        raise die(f"{context}: cannot determine wrapper return type")
    brace = block.find("{", wrapper_end)
    if brace < 0:
        raise die(f"{context}: wrapper has no body")

    ret = RETURN.search(block, brace)
    if not ret:
        raise die(f"{context}: wrapper has no __riscv_* return call")
    call_args, call_end = balanced_contents(
        block, ret.end() - 1, f"{context}: C call arguments"
    )
    if not re.match(r"\s*;", block[call_end:]):
        raise die(f"{context}: malformed intrinsic return statement")
    if ret.group("name") != "__riscv_" + label.group("name")[5:]:
        # Zvzip's generated wrapper and actual call use different result-type
        # suffixes.  The call name remains canonical, but arbitrary mismatches
        # elsewhere are suspicious.
        if "/zvzip/" not in path.as_posix():
            raise die(
                f"{context}: label {label.group('name')} calls {ret.group('name')}"
            )

    return Unit(
        path=path,
        line=line,
        check=block[: wrapper.start()],
        return_type=return_type,
        wrapper_name=wrapper.group("name"),
        wrapper_params=parse_params(wrapper_params, f"{context}: wrapper parameters"),
        intrinsic_name=ret.group("name"),
        call_args=tuple(split_top_level(call_args, f"{context}: C call arguments")),
    )


def units_in_file(path: Path) -> Iterable[Unit]:
    text = path.read_text(encoding="utf-8")
    labels = list(LABEL.finditer(text))
    if len(labels) != len(LABEL_PREFIX.findall(text)):
        raise die(f"{path}: malformed CHECK-RV64-LABEL line")
    for index, match in enumerate(labels):
        end = labels[index + 1].start() if index + 1 < len(labels) else len(text)
        # A few generated Clang tests put a long wrapper's return type on the
        # line immediately before its CHECK label, then continue with the
        # function name after the checks. Preserve that generated spelling.
        previous_line = text[: match.start()].rsplit("\n", 2)[-2].strip()
        leading_return = (
            previous_line
            if previous_line
            and not previous_line.startswith("//")
            and re.fullmatch(r"[A-Za-z_][A-Za-z0-9_ ]*", previous_line)
            else None
        )
        yield parse_unit(
            path,
            text[match.start() : end],
            text.count("\n", 0, match.start()) + 1,
            leading_return,
        )


def call_from_check(unit: Unit) -> Tuple[str, Tuple[str, ...]]:
    calls = []
    for match in CALL_START.finditer(unit.check):
        args, _ = balanced_contents(
            unit.check, match.end() - 1, f"{unit.where()}: LLVM call arguments"
        )
        calls.append(
            (
                match.group("name"),
                tuple(split_top_level(args, f"{unit.where()}: LLVM call arguments")),
            )
        )
    if not calls:
        raise die(f"{unit.where()}: no llvm.riscv call in CHECK-RV64 body")
    if len(calls) != 1:
        names = ", ".join(name for name, _ in calls)
        raise die(f"{unit.where()}: expected one llvm.riscv call, found {names}")
    return calls[0]


def rv32_calls(
    path: Path, clang: Path
) -> Optional[Dict[str, Tuple[str, Tuple[str, ...]]]]:
    """Compile one generated test for RV32 and return calls by wrapper name."""
    run_lines = [
        line.removeprefix("// RUN:").strip().removesuffix("\\").strip()
        for line in path.read_text(encoding="utf-8").splitlines()
        if line.startswith("// RUN:")
    ]
    command = " ".join(run_lines).split("|", 1)[0]
    if not command.startswith("%clang_cc1 "):
        raise die(f"{path}: cannot find clang_cc1 RUN line")
    args = shlex.split(command.removeprefix("%clang_cc1 "))
    args = [str(path) if arg == "%s" else arg for arg in args]
    triple = args.index("-triple") + 1
    if args[triple] != "riscv64":
        raise die(f"{path}: expected riscv64 RUN triple")
    args[triple] = "riscv32"
    compiled = subprocess.run(
        [str(clang), "-cc1", *args],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    if compiled.returncode != 0:
        errors = [line for line in compiled.stderr.splitlines() if "error:" in line]
        expected = (
            path.name in RV64_ONLY_FILES
            and errors
            and all(
                "builtin requires at least one of the following extensions: 64bit" in line
                for line in errors
            )
        )
        if not expected:
            raise die(f"{path}: RV32 clang failed:\n{compiled.stderr.strip()}")
        return None
    output = compiled.stdout

    calls = {}
    current = None
    for line in output.splitlines():
        if line.startswith("define "):
            match = re.search(r"@(?P<name>test_[A-Za-z0-9_]+)\(", line)
            current = match.group("name") if match else None
        elif current is not None and " call " in line and "@llvm.riscv." in line:
            match = CALL_START.search(line)
            if match is None:
                raise die(f"{path}: malformed RV32 LLVM call for {current}")
            operands, _ = balanced_contents(
                line, match.end() - 1, f"{path}: RV32 LLVM call operands"
            )
            if current in calls:
                # Structural wrappers can contain several LLVM calls. They are
                # excluded by `extract_files`, so keep their first call here.
                continue
            calls[current] = (
                match.group("name"),
                tuple(split_top_level(operands, f"{path}: RV32 LLVM operands")),
            )
        elif line == "}":
            current = None
    return calls


def xlen_mangling(rv64: str, rv32: str, context: str) -> str:
    """Mark every target-dependent overload occurrence as `iXLEN`."""
    parts64 = rv64.split(".")
    parts32 = rv32.split(".")
    if len(parts64) != len(parts32):
        raise die(f"{context}: RV32/RV64 mangling length differs")
    result = []
    for part64, part32 in zip(parts64, parts32):
        if part64 == part32:
            result.append(part64)
        elif (part64, part32) in (("i64", "i32"), ("iXLEN", "i32")):
            result.append("iXLEN")
        else:
            raise die(
                f"{context}: unexpected RV32/RV64 overload difference "
                f"{part64!r} vs {part32!r}"
            )
    return ".".join(result)


def hidden_uimm_family(unit: Unit) -> Optional[str]:
    for family in HIDDEN_UIMM_FAMILIES:
        if unit.intrinsic_name.startswith(f"__riscv_{family}_"):
            return family
    return None


def source_params(
    unit: Unit, restore_hidden_uimm: bool = False
) -> Tuple[Tuple[Param, ...], Dict[str, int], Dict[str, Tuple[int, int]]]:
    """Build real intrinsic params, restoring omitted RM/uimm parameters."""
    wrapper: Dict[str, Param] = {}
    for param in unit.wrapper_params:
        key = param.name.lower()
        if key in wrapper:
            raise die(f"{unit.where()}: duplicate wrapper parameter {param.name!r}")
        wrapper[key] = param
    params: List[Param] = []
    indices: Dict[str, int] = {}
    constant_params: Dict[str, Tuple[int, int]] = {}
    seen_wrapper = set()
    for raw in unit.call_args:
        token = raw.strip()
        rm = RM_MACRO.fullmatch(token)
        if rm:
            name = "frm" if rm.group("kind") == "FRM" else "vxrm"
            if name in constant_params:
                raise die(f"{unit.where()}: duplicate {name} macro argument")
            constant_params[name] = (len(params), 0)
            params.append(Param(f"size_t {name}", name))
            continue
        literal = re.fullmatch(r"([+-]?\d+)", token)
        if literal:
            family = hidden_uimm_family(unit)
            if not restore_hidden_uimm or family is None:
                raise die(f"{unit.where()}: invalid C call argument {token!r}")
            if "uimm" in constant_params:
                raise die(f"{unit.where()}: more than one hidden uimm literal")
            constant_params["uimm"] = (len(params), int(literal.group(1)))
            params.append(Param("size_t uimm", "uimm"))
            continue
        if not IDENT.fullmatch(token):
            raise die(f"{unit.where()}: invalid C call argument {token!r}")
        key = token.lower()
        if key not in wrapper:
            raise die(f"{unit.where()}: C call argument {token!r} is not a wrapper parameter")
        if key in seen_wrapper:
            raise die(f"{unit.where()}: wrapper parameter {token!r} is used more than once")
        seen_wrapper.add(key)
        indices[key] = len(params)
        params.append(wrapper[key])
    missing = sorted(set(wrapper) - seen_wrapper)
    if missing:
        raise die(f"{unit.where()}: wrapper parameters not mapped by C call: {missing}")
    if restore_hidden_uimm and hidden_uimm_family(unit) is not None:
        if "uimm" not in constant_params:
            raise die(f"{unit.where()}: expected exactly one hidden uimm literal")
    return tuple(params), indices, constant_params


def classify_operands(
    unit: Unit,
    ir_args: Sequence[str],
    indices: Dict[str, int],
    constant_params: Dict[str, Tuple[int, int]],
) -> Tuple[str, ...]:
    ops: List[Optional[str]] = []
    integer_positions: List[int] = []
    for ir_arg in ir_args:
        low = ir_arg.lower()
        if re.search(r"\b(?:poison|undef)\b", low):
            ops.append("poison")
            continue
        placeholders = [name.lower() for name in PLACEHOLDER.findall(ir_arg)]
        if placeholders:
            mapped = {indices[name] for name in placeholders if name in indices}
            if len(mapped) == 1 and all(name in indices for name in placeholders):
                ops.append(str(mapped.pop()))
                continue
            unknown = sorted(set(placeholders) - set(indices))
            raise die(
                f"{unit.where()}: opaque LLVM operand {ir_arg!r}"
                + (f" (unknown placeholders: {unknown})" if unknown else "")
            )
        integer = INTEGER.fullmatch(ir_arg.strip())
        if integer:
            integer_positions.append(len(ops))
            ops.append(f"#i{integer.group('width')}:{integer.group('value')}")
            continue
        raise die(f"{unit.where()}: opaque LLVM operand {ir_arg!r}")

    # Generated wrappers materialize explicit RM macros and a few crypto uimm
    # arguments as constants. Bind by value and position: the public parameter
    # precedes VL, whereas any independent policy constant follows VL.
    for param_name, (param_index, literal) in constant_params.items():
        candidates = [
            pos
            for pos in integer_positions
            if ops[pos].rsplit(":", 1)[-1] == str(literal)
            and any(
                later is not None and later.isdigit() and int(later) > param_index
                for later in ops[pos + 1 :]
            )
        ]
        if len(candidates) != 1:
            raise die(
                f"{unit.where()}: cannot uniquely bind {param_name} to an LLVM "
                f"iN {literal} operand"
            )
        ops[candidates[0]] = str(param_index)
    return tuple(op for op in ops if op is not None)


def scalar_abi_type(c_type: str) -> Optional[str]:
    """Return the LLVM integer class exposed by a C scalar parameter."""
    c_type = normalize_space(c_type)
    if c_type in ("size_t", "ptrdiff_t"):
        return "xlen"
    integer = re.fullmatch(r"(?:u?int)(8|16|32|64)_t", c_type)
    return f"i{integer.group(1)}" if integer else None


def type_constants(entries: Dict[str, Entry], unresolved: set[str]) -> Dict[str, Entry]:
    """Attach the unique LLVM integer type to every literal operand slot.

    Clang's CHECK lines provide each literal's concrete RV64 `iN` type.  For
    `i64`, which may mean either fixed i64 or XLEN, another API using the same
    mangled intrinsic and operand slot supplies an authoritative scalar C type.
    LLVM MatchType control operands are then constrained by the preceding XLEN
    operand (normally VL), or by an XLEN return for vsetvl[i|max].
    """
    witnesses: Dict[Tuple[str, int], set[str]] = {}
    for entry in entries.values():
        param_types = entry.signature[1:]
        for slot, operand in enumerate(entry.ops):
            if operand.isdigit():
                ty = scalar_abi_type(param_types[int(operand)])
                if ty is not None:
                    witnesses.setdefault((entry.llvm, slot), set()).add(ty)

    result: Dict[str, Entry] = {}
    for name, entry in entries.items():
        if name not in unresolved:
            result[name] = entry
            continue
        typed: List[str] = []
        slot_types: List[Optional[str]] = []
        param_types = entry.signature[1:]
        for slot, operand in enumerate(entry.ops):
            if not operand.startswith("#"):
                typed.append(operand)
                slot_types.append(
                    scalar_abi_type(param_types[int(operand)])
                    if operand.isdigit()
                    else None
                )
                continue
            llvm_ty, value = operand[1:].split(":", 1)
            candidates = witnesses.get((entry.llvm, slot), set())
            if len(candidates) > 1:
                raise die(
                    f"{entry.source}: conflicting types for {entry.llvm} "
                    f"operand {slot}: {sorted(candidates)}"
                )
            if llvm_ty != "i64":
                ty = llvm_ty
            elif candidates:
                ty = next(iter(candidates))
            elif (slot_types and slot_types[-1] == "xlen") or (
                scalar_abi_type(entry.signature[0]) == "xlen"
            ):
                ty = "xlen"
            else:
                raise die(
                    f"{entry.source}: cannot uniquely type {entry.llvm} "
                    f"operand {slot}"
                )
            typed.append(f"#{ty}:{value}")
            slot_types.append(ty)
        result[name] = replace(entry, ops=tuple(typed))
    return result


def extract_unit(unit: Unit, restore_hidden_uimm: bool = False) -> Entry:
    params, indices, constant_params = source_params(unit, restore_hidden_uimm)
    llvm, ir_args = call_from_check(unit)
    ops = classify_operands(unit, ir_args, indices, constant_params)
    if restore_hidden_uimm:
        # These crypto intrinsics have both an iXLEN immediate overload and an
        # iXLEN VL overload. Preserve both slots for RV32 rather than relying
        # on the legacy "replace the final .i64" convention.
        llvm = llvm.replace(".i64", ".iXLEN")
    prototype = (
        f"{unit.return_type} {unit.intrinsic_name}"
        f"({', '.join(param.declaration for param in params) or 'void'})"
    )
    param_types = tuple(
        re.sub(rf"\b{re.escape(param.name)}\b\s*$", "", param.declaration).strip()
        for param in params
    )
    return Entry(llvm, ops, prototype, (unit.return_type, *param_types), unit.where())


def add_entry(
    entries: Dict[str, Entry], name: str, entry: Entry, duplicates: List[int]
) -> None:
    old = entries.get(name)
    if old is None:
        entries[name] = entry
    elif (old.llvm, old.ops, old.signature) == (entry.llvm, entry.ops, entry.signature):
        # The extension-specific directories duplicate a small part of base
        # with different, semantically irrelevant parameter names. The legacy
        # TSV stores only name/LLVM/ops, so identical typed recipes are the
        # same record. Prefer the later, more specific prototype for policy
        # companion validation.
        duplicates[0] += 1
        entries[name] = entry
    else:
        raise die(
            f"conflicting duplicate {name}:\n  first: {old.source} -> "
            f"{old.llvm} {','.join(old.ops)}\n  later: {entry.source} -> "
            f"{entry.llvm} {','.join(entry.ops)}"
        )


def c_files(path: Path) -> List[Path]:
    if path.is_file():
        if path.suffix != ".c":
            raise die(f"policy source is not a .c file: {path}")
        return [path]
    if not path.is_dir():
        raise die(f"input path does not exist: {path}")
    files = sorted(path.rglob("*.c"), key=lambda item: item.as_posix())
    if not files:
        raise die(f"input directory contains no .c files: {path}")
    return files


def non_policy_name(name: str) -> Optional[str]:
    for suffix in ("_tumu", "_tum", "_mu", "_tu"):
        if name.endswith(suffix):
            stem = name[: -len(suffix)]
            return stem + ("_m" if suffix != "_tu" else "")
    return None


def ofp8_family_counts(entries: Dict[str, Entry]) -> Dict[str, int]:
    counts = Counter()
    for name in entries:
        for family in EXPECTED_OFP8_FAMILIES:
            if name.startswith(family):
                counts[family] += 1
                break
        else:
            raise die(f"unexpected Zvfofp8min API {name}")
    return dict(counts)


def validate_ofp8_pair(
    policy: Dict[str, Entry], non_policy: Dict[str, Entry]
) -> None:
    """Require the selected Zvfofp8min policy and source sets to match both ways."""
    if len(policy) != EXPECTED_OFP8_POLICY:
        raise die(
            f"expected {EXPECTED_OFP8_POLICY} Zvfofp8min policy "
            f"APIs, found {len(policy)}"
        )
    if len(non_policy) != EXPECTED_OFP8_NON_POLICY:
        raise die(
            f"expected {EXPECTED_OFP8_NON_POLICY} Zvfofp8min "
            f"non-policy APIs, found {len(non_policy)}"
        )

    suffixes = Counter(
        next(suffix for suffix in POLICY_SUFFIXES if name.endswith(suffix))
        for name in policy
    )
    expected_suffixes = {suffix: 100 for suffix in POLICY_SUFFIXES}
    if dict(suffixes) != expected_suffixes:
        raise die(
            "unexpected Zvfofp8min policy suffix counts: "
            f"expected {expected_suffixes}, found {dict(suffixes)}"
        )

    policy_sources = {
        non_policy_name(name)
        for name in policy
        if non_policy_name(name) is not None
    }
    source_names = set(non_policy)
    missing = sorted(policy_sources - source_names)
    uncovered = sorted(source_names - policy_sources)
    if missing or uncovered:
        raise die(
            "Zvfofp8min policy/non-policy surface mismatch: "
            f"missing sources={missing}, uncovered sources={uncovered}"
        )
    multiplicities = Counter(non_policy_name(name) for name in policy)
    expected_multiplicities = Counter({1: 100, 3: 100})
    actual_multiplicities = Counter(multiplicities.values())
    if actual_multiplicities != expected_multiplicities:
        raise die(
            "unexpected Zvfofp8min policy/source multiplicities: "
            f"expected {dict(expected_multiplicities)}, "
            f"found {dict(actual_multiplicities)}"
        )

    family_counts = ofp8_family_counts(non_policy)
    if family_counts != EXPECTED_OFP8_FAMILIES:
        raise die(
            "unexpected Zvfofp8min family counts: "
            f"expected {EXPECTED_OFP8_FAMILIES}, found {family_counts}"
        )


def ofp8_files(root: Path, policy_only: bool) -> List[Path]:
    relative = OFP8_POLICY_DIR if policy_only else OFP8_NON_POLICY_DIR
    return [root / relative / filename for filename in OFP8_FILES]


def validate_uimm_companion(unit: Unit, entry: Entry, companion: Entry) -> None:
    if entry.signature[0] != companion.signature[0]:
        raise die(f"{unit.where()}: policy/non-policy return type mismatch")
    policy_types = list(entry.signature[1:])
    source_types = list(companion.signature[1:])
    suffix = next(suffix for suffix in POLICY_SUFFIXES if unit.intrinsic_name.endswith(suffix))
    passthru = 0 if suffix == "_tu" else 1
    inherited = policy_types == source_types
    inserted = (
        len(policy_types) == len(source_types) + 1
        and policy_types[passthru] == entry.signature[0]
        and policy_types[:passthru] + policy_types[passthru + 1 :] == source_types
    )
    if not inherited and not inserted:
        raise die(
            f"{unit.where()}: restored uimm signature does not match companion "
            f"{companion.source}"
        )


def extract_files(
    files: Sequence[Path],
    policy_only: bool,
    uimm_companions: Optional[Dict[str, Entry]] = None,
    clang: Optional[Path] = None,
) -> Tuple[Dict[str, Entry], int]:
    entries: Dict[str, Entry] = {}
    duplicates = [0]
    unresolved = set()
    for path in files:
        rv32 = rv32_calls(path, clang) if clang is not None else None
        for unit in units_in_file(path):
            if policy_only and not unit.intrinsic_name.endswith(POLICY_SUFFIXES):
                continue
            if any(
                unit.intrinsic_name.startswith(prefix)
                for prefix in STRUCTURAL_FAMILIES
            ):
                # These are intentionally implemented with generic LLVM IR
                # operations, not llvm.riscv intrinsics.  Naming the complete
                # allowlist makes this exclusion auditable and keeps an
                # unexpected missing CALL fatal everywhere else.
                continue
            restore_uimm = bool(
                policy_only
                and hidden_uimm_family(unit)
                and any(re.fullmatch(r"[+-]?\d+", arg) for arg in unit.call_args)
            )
            entry = extract_unit(unit, restore_uimm)
            if rv32 is not None:
                rv32_call = rv32.get(unit.wrapper_name)
                if rv32_call is None:
                    raise die(f"{unit.where()}: missing RV32 LLVM call")
                rv32_llvm, rv32_args = rv32_call
                if len(rv32_args) != len(entry.ops):
                    raise die(f"{unit.where()}: RV32/RV64 operand count differs")
                typed_ops = []
                for slot, operand in enumerate(entry.ops):
                    if not operand.startswith("#"):
                        typed_ops.append(operand)
                        continue
                    rv64_ty, value = operand[1:].split(":", 1)
                    rv32_integer = INTEGER.fullmatch(rv32_args[slot].strip())
                    if rv32_integer is None or rv32_integer.group("value") != value:
                        raise die(
                            f"{unit.where()}: RV32 literal differs at operand {slot}"
                        )
                    rv32_ty = f"i{rv32_integer.group('width')}"
                    ty = "xlen" if (rv64_ty, rv32_ty) == ("i64", "i32") else rv64_ty
                    if ty != "xlen" and rv64_ty != rv32_ty:
                        raise die(
                            f"{unit.where()}: unsupported target-dependent literal "
                            f"type {rv64_ty}/{rv32_ty} at operand {slot}"
                        )
                    typed_ops.append(f"#{ty}:{value}")
                entry = replace(
                    entry,
                    llvm=xlen_mangling(entry.llvm, rv32_llvm, unit.where()),
                    ops=tuple(typed_ops),
                )
                unresolved.discard(unit.intrinsic_name)
            else:
                unresolved.add(unit.intrinsic_name)
            if restore_uimm:
                source_name = non_policy_name(unit.intrinsic_name)
                companion = (uimm_companions or {}).get(source_name or "")
                if companion is None:
                    raise die(
                        f"{unit.where()}: no non-policy companion for hidden uimm"
                    )
                validate_uimm_companion(unit, entry, companion)
            add_entry(entries, unit.intrinsic_name, entry, duplicates)
    return type_constants(entries, unresolved), duplicates[0]


def is_segment_name(name: str) -> bool:
    """Match the segment families owned by Rust's compiler bridge."""
    short = name.removeprefix("__riscv_")
    position = short.find("seg")
    return (
        position >= 0
        and position + 3 < len(short)
        and short[position + 3].isdigit()
    )


def rust_lowering_exclusion(name: str) -> Optional[str]:
    if is_segment_name(name):
        return "segment compiler bridge"
    if "bf16" in name:
        return "programmatic or sibling-derived BF16"
    return None


def select_rust_lowering(entries: Dict[str, Entry]) -> Dict[str, Entry]:
    excluded = Counter()
    selected = {}
    for name, entry in entries.items():
        reason = rust_lowering_exclusion(name)
        if reason is None:
            selected[name] = entry
        else:
            excluded[reason] += 1
    if dict(excluded) != EXPECTED_RUST_EXCLUSIONS:
        raise die(
            "unexpected Rust lowering exclusion counts: "
            f"expected {EXPECTED_RUST_EXCLUSIONS}, found {dict(excluded)}"
        )
    if len(selected) != EXPECTED_AUTOGEN_RUST_LOWERING:
        raise die(
            f"expected {EXPECTED_AUTOGEN_RUST_LOWERING} selected autogenerated "
            f"Rust lowering entries, found {len(selected)}"
        )
    return selected


def parse_policy_source(value: str) -> Tuple[str, str]:
    if "=" not in value:
        raise argparse.ArgumentTypeError("expected SCOPE=RELATIVE_PATH")
    scope, relative = value.split("=", 1)
    if not SCOPE.fullmatch(scope) or not relative or Path(relative).is_absolute():
        raise argparse.ArgumentTypeError("expected identifier SCOPE and relative path")
    return scope, relative


def load_uimm_companions(root: Path) -> Dict[str, Entry]:
    """Load the four non-policy prototypes that expose hidden uimm roles."""
    entries: Dict[str, Entry] = {}
    for family in sorted(HIDDEN_UIMM_FAMILIES):
        path = root / f"vector-crypto/non-policy/non-overloaded/{family}.c"
        for unit in units_in_file(path):
            if hidden_uimm_family(unit) != family:
                raise die(f"{unit.where()}: unexpected companion family")
            if unit.intrinsic_name in entries:
                raise die(f"{unit.where()}: duplicate non-policy uimm companion")
            entries[unit.intrinsic_name] = extract_unit(unit, True)
    return entries


def clang_provenance(root: Path) -> Tuple[str, str]:
    project = root
    while project != project.parent:
        if (project / "cmake/Modules/LLVMVersion.cmake").is_file():
            break
        project = project.parent
    version = "unknown"
    version_file = project / "cmake/Modules/LLVMVersion.cmake"
    if version_file.is_file():
        values = {}
        for key, value in re.findall(
            r"set\(LLVM_VERSION_(MAJOR|MINOR|PATCH)\s+([^\s)]+)",
            version_file.read_text(encoding="utf-8"),
        ):
            values[key] = value
        if all(key in values for key in ("MAJOR", "MINOR", "PATCH")):
            version = f"{values['MAJOR']}.{values['MINOR']}.{values['PATCH']}"
    commit = "unknown"
    try:
        commit = subprocess.run(
            ["git", "-C", str(project), "rev-parse", "HEAD"],
            check=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL,
            text=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        pass
    return version, commit


def validate_clang_provenance(root: Path, clang: Path) -> None:
    """Reject a Clang binary that does not match the source being parsed."""
    source_version, source_commit = clang_provenance(root)
    compiled = subprocess.run(
        [str(clang), "--version"],
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        text=True,
    )
    if compiled.returncode != 0:
        raise die(f"cannot query clang version: {compiled.stderr.strip()}")
    output = compiled.stdout
    first_line = output.splitlines()[0] if output else ""
    if source_version != "unknown" and f"clang version {source_version}" not in first_line:
        raise die(
            f"clang version does not match source {source_version}: {first_line!r}"
        )
    commits = re.findall(r"\b[0-9a-f]{12,40}\b", first_line)
    if source_commit != "unknown":
        if not commits or not any(
            source_commit.startswith(commit) or commit.startswith(source_commit)
            for commit in commits
        ):
            raise die(
                f"clang commit does not match source {source_commit}: {first_line!r}"
            )


def write_legacy(path: Path, entries: Dict[str, Entry]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as output:
        output.write("# format: rvv-lowering-v2\n")
        for name in sorted(entries):
            entry = entries[name]
            output.write(f"{name}\t{entry.llvm}\t{','.join(entry.ops)}\n")


def write_policy(
    path: Path,
    root: Path,
    sources: Sequence[Tuple[str, str, Sequence[Path]]],
    entries: Dict[str, Tuple[str, Entry]],
) -> None:
    version, commit = clang_provenance(root)
    source_text = ",".join(f"{scope}={relative}" for scope, relative, _ in sources)
    with path.open("w", encoding="utf-8", newline="\n") as output:
        output.write("# format: rvv-policy-v2\n")
        output.write(f"# clang-version: {version}\n")
        output.write(f"# clang-commit: {commit}\n")
        output.write(f"# source-dirs: {source_text}\n")
        for name, (scope, entry) in sorted(
            entries.items(), key=lambda item: (item[1][0], item[0])
        ):
            output.write(
                f"{scope}\t{entry.prototype}\t{entry.llvm}\t{','.join(entry.ops)}\n"
            )


def parser() -> argparse.ArgumentParser:
    result = argparse.ArgumentParser(description=__doc__)
    result.add_argument("clang_autogen_root", type=Path)
    result.add_argument("out_file", type=Path)
    result.add_argument(
        "--rust-lowering",
        action="store_true",
        help="emit the exact lowering subset owned by Rust's checked-in oracle",
    )
    result.add_argument(
        "--sifive-root",
        type=Path,
        metavar="PATH",
        help=argparse.SUPPRESS,
    )
    result.add_argument(
        "--clang",
        type=Path,
        help="clang binary used to preserve RV32/RV64 operand-slot types",
    )
    result.add_argument("--policy-out", type=Path, metavar="PATH")
    result.add_argument(
        "--policy-source",
        action="append",
        default=[],
        type=parse_policy_source,
        metavar="SCOPE=RELATIVE_PATH",
        help="replace the default policy allowlist (repeatable; path is below clang-autogen-root)",
    )
    return result


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = parser().parse_args(argv)
    try:
        root = args.clang_autogen_root.resolve()
        if args.clang is None:
            raise die("--clang is required to preserve RV32/RV64 operand types")
        args.clang = args.clang.resolve()
        if not args.clang.is_file():
            raise die(f"clang binary does not exist: {args.clang}")
        validate_clang_provenance(root, args.clang)
        if args.policy_out is not None and args.out_file.resolve() == args.policy_out.resolve():
            raise die("out-file and --policy-out must be different paths")
        needs_ofp8 = args.rust_lowering or (
            args.policy_out is not None and not args.policy_source
        )
        ofp8_root = (
            args.sifive_root.resolve()
            if args.sifive_root is not None
            else root
        )
        if args.sifive_root is not None and not needs_ofp8:
            raise die("--sifive-root requires --rust-lowering or default --policy-out")

        ofp8_non_policy: Dict[str, Entry] = {}
        if needs_ofp8:
            ofp8_non_policy, ofp8_duplicates = extract_files(
                ofp8_files(ofp8_root, False),
                policy_only=False,
                clang=args.clang,
            )
            if ofp8_duplicates:
                raise die(
                    "expected no duplicate Zvfofp8min non-policy APIs, "
                    f"found {ofp8_duplicates}"
                )
            if len(ofp8_non_policy) != EXPECTED_OFP8_NON_POLICY:
                raise die(
                    f"expected {EXPECTED_OFP8_NON_POLICY} "
                    f"Zvfofp8min non-policy APIs, found {len(ofp8_non_policy)}"
                )
            family_counts = ofp8_family_counts(ofp8_non_policy)
            if family_counts != EXPECTED_OFP8_FAMILIES:
                raise die(
                    "unexpected SiFive Zvfofp8min family counts: "
                    f"expected {EXPECTED_OFP8_FAMILIES}, found {family_counts}"
                )

        if args.rust_lowering:
            if not (root / "non-policy/non-overloaded").is_dir():
                raise die("--rust-lowering requires an rvv-intrinsics-autogenerated root")
            autogen_files = [
                file
                for relative in RUST_LOWERING_DIRS
                for file in c_files(root / relative)
            ]
            extracted, legacy_duplicates = extract_files(
                autogen_files, policy_only=False, clang=args.clang
            )
            legacy = select_rust_lowering(extracted)
            duplicate_counter = [legacy_duplicates]
            for name, entry in ofp8_non_policy.items():
                add_entry(legacy, name, entry, duplicate_counter)
            legacy_duplicates = duplicate_counter[0]
            if len(legacy) != EXPECTED_RUST_LOWERING:
                raise die(
                    f"expected {EXPECTED_RUST_LOWERING} Rust lowering entries, "
                    f"found {len(legacy)}"
                )
        elif (root / "non-policy/non-overloaded").is_dir():
            legacy_files = [
                file
                for relative in LEGACY_LOWERING_DIRS
                for file in c_files(root / relative)
            ]
            legacy, legacy_duplicates = extract_files(
                legacy_files, policy_only=False, clang=args.clang
            )
        else:
            # Preserve the old ability to point directly at a selected leaf.
            legacy_files = c_files(root)
            legacy, legacy_duplicates = extract_files(
                legacy_files, policy_only=False, clang=args.clang
            )

        policy = {}
        policy_duplicates = 0
        sources = []
        if args.policy_out is not None:
            selected: List[Tuple[str, str, List[Path]]] = []
            for scope, relative in args.policy_source or list(POLICY_DIRS):
                source_path = (root / relative).resolve()
                try:
                    source_path.relative_to(root)
                except ValueError:
                    raise die(f"policy source escapes clang-autogen-root: {relative}")
                files = c_files(source_path)
                canonical_relative = source_path.relative_to(root).as_posix()
                selected.append((scope, canonical_relative, files))
            if not args.policy_source:
                for source_path in ofp8_files(ofp8_root, True):
                    relative = Path(os.path.relpath(source_path, root)).as_posix()
                    selected.append(("zvfofp8min", relative, c_files(source_path)))
            uimm_companions = load_uimm_companions(root)
            ofp8_policy: Dict[str, Entry] = {}
            ofp8_policy_duplicates = [0]
            for scope, canonical_relative, files in selected:
                sources.append((scope, canonical_relative, files))
                scoped, duplicates = extract_files(
                    files,
                    policy_only=True,
                    uimm_companions=uimm_companions,
                    clang=args.clang,
                )
                policy_duplicates += duplicates
                if scope == "zvfofp8min":
                    for name, entry in scoped.items():
                        add_entry(
                            ofp8_policy, name, entry, ofp8_policy_duplicates
                        )
                for name, entry in scoped.items():
                    old = policy.get(name)
                    candidate = (scope, entry)
                    if old is None:
                        policy[name] = candidate
                    elif (old[1].llvm, old[1].ops, old[1].signature) == (
                        entry.llvm, entry.ops, entry.signature
                    ):
                        # Some extension directories duplicate base coverage
                        # but use different, semantically irrelevant parameter
                        # names.  Prefer the more specific later scope while
                        # requiring the lowering recipe to remain identical.
                        policy_duplicates += 1
                        policy[name] = candidate
                    else:
                        raise die(
                            f"conflicting policy duplicate {name}: {old[1].source} and {entry.source}"
                        )
            if not args.policy_source:
                if ofp8_policy_duplicates[0]:
                    raise die(
                        "expected no duplicate Zvfofp8min policy APIs, "
                        f"found {ofp8_policy_duplicates[0]}"
                    )
                validate_ofp8_pair(ofp8_policy, ofp8_non_policy)

        # Do not create either output until every requested input has passed.
        write_legacy(args.out_file, legacy)
        sys.stderr.write(
            f"wrote {len(legacy)} oracle entries to {args.out_file} "
            f"({legacy_duplicates} identical duplicates)\n"
        )
        if args.policy_out is not None:
            write_policy(args.policy_out, root, sources, policy)
            sys.stderr.write(
                f"wrote {len(policy)} policy entries to {args.policy_out} "
                f"({policy_duplicates} identical duplicates)\n"
            )
        return 0
    except (ExtractError, OSError, UnicodeError) as error:
        parser().exit(1, f"error: {error}\n")


if __name__ == "__main__":
    sys.exit(main())
